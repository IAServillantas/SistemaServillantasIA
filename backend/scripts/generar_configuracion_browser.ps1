param([switch]$Check)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '_paths.ps1')
$rules = Get-Content -LiteralPath $script:ConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json
$json = $rules | ConvertTo-Json -Depth 10 -Compress
$content = "// GENERATED by backend/scripts/generar_configuracion_browser.ps1. Edit backend/config/inventory-rules.json only.`nwindow.INVENTORY_RULES = $json;`n"
$target = Join-Path $script:SharedRoot 'inventory-config.js'
if ($Check) {
    if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -cne $content) {
        throw 'Configuracion JavaScript desactualizada. Ejecute generar_configuracion_browser.ps1.'
    }
} else {
    [IO.File]::WriteAllText($target, $content, [Text.UTF8Encoding]::new($false))
}
