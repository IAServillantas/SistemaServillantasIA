param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$rules = Get-Content -LiteralPath (Join-Path $root 'config/inventory-rules.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$json = $rules | ConvertTo-Json -Depth 10 -Compress
$content = "// GENERATED by scripts/generar_configuracion_browser.ps1. Edit config/inventory-rules.json only.`nwindow.INVENTORY_RULES = $json;`n"
$target = Join-Path $root 'shared/inventory-config.js'
if ($Check) {
    if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -cne $content) {
        throw 'Configuracion JavaScript desactualizada. Ejecute generar_configuracion_browser.ps1.'
    }
} else {
    [IO.File]::WriteAllText($target, $content, [Text.UTF8Encoding]::new($false))
}
