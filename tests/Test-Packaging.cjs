const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {root,dashboard,LEGACY}=require('./dashboard-harness.cjs');
const pages=['frontend/inventario','frontend/criticas','frontend/chihuahua'];
for(const folder of pages) {
 test(`${folder}: pagina tiene shell operativo`,()=>{
  const html=fs.readFileSync(path.join(root,folder,'index.html'),'utf8');
  assert.match(html,/id="excelInput"/);
  assert.match(html,/id="cloudLoadButton"/);
  assert.match(html,/inventory-sync\.js/);
  assert.match(html,/supabase-config\.js/);
  assert.ok(LEGACY[folder]);
 });
}
for(const name of ['dashboard_inventario_local','dashboard_servillantas_chihuahua_local']) {
 const folder='backend/distribucion/'+name;
 test(`${name}: scripts available offline and startup succeeds`,()=>{
  const html=fs.readFileSync(path.join(root,folder,'index.html'),'utf8');
  for(const match of html.matchAll(/<script src="([^"]+)"/g)) {
   assert.ok(fs.existsSync(path.resolve(root,folder,match[1])),match[1]);
  }
  for(const asset of ['inventory.js','inventory-config.js']) {
   assert.equal(
     fs.readFileSync(path.join(root,folder,'shared',asset),'utf8').replace(/\r\n/g,'\n').replace(/^\/\/ GENERATED by .*\n/,''),
     fs.readFileSync(path.join(root,'frontend/shared',asset),'utf8').replace(/\r\n/g,'\n').replace(/^\/\/ GENERATED by .*\n/,'')
   );
  }
  const {api}=dashboard(folder);
  assert.equal(api.getSource().rows.length,0);
 });
}
